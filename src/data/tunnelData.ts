export function generateHwid(): string {
  const seg = () =>
    Math.floor(0x1000 + Math.random() * 0xefff)
      .toString(16)
      .toUpperCase();
  return `HXPC-${seg()}-${seg()}-${seg()}-${seg()}`;
}
